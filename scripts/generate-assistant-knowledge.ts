// Builds the assistant's searchable knowledge from the in-app guide content and selected docs.
// Run via `npm run assistant:knowledge` (the aws build scripts call it automatically).
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEFAULT_WORKFLOW_GUIDE_CONTENT } from '../src/components/tabs/workflowGuideContent';

type Audience = 'all' | 'full-access' | 'workflow';

interface Chunk {
  id: string;
  source: string;
  title: string;
  text: string;
  audience: Audience;
  roles?: string[];
  pages?: string[];
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const outFile = path.join(root, 'aws/src/providers/ai/assistant/knowledge.generated.ts');
const MAX_CHUNK = 1800;
const chunks: Chunk[] = [];

function add(chunk: Omit<Chunk, 'id'>) {
  chunks.push({ id: `${chunk.source}#${chunks.length}`, ...chunk });
}

function splitLong(text: string): string[] {
  if (text.length <= MAX_CHUNK) return [text];
  const parts: string[] = [];
  let current = '';
  for (const line of text.split('\n')) {
    if (current && current.length + line.length > MAX_CHUNK) {
      parts.push(current.trim());
      current = '';
    }
    current += `${line}\n`;
  }
  if (current.trim()) parts.push(current.trim());
  return parts;
}

function addMarkdown(file: string, source: string, audience: Audience) {
  const body = readFileSync(path.join(root, file), 'utf8');
  let heading = source;
  let buffer: string[] = [];
  const flush = () => {
    const text = buffer.join('\n').trim();
    buffer = [];
    if (!text) return;
    splitLong(text).forEach((part, index) => add({ source, title: index ? `${heading} (cont.)` : heading, text: part, audience }));
  };
  for (const line of body.split('\n')) {
    const match = /^#{1,3}\s+(.*)$/.exec(line);
    if (match) {
      flush();
      heading = match[1].trim();
    } else {
      buffer.push(line);
    }
  }
  flush();
}

const guide = DEFAULT_WORKFLOW_GUIDE_CONTENT;

for (const [role, roleGuide] of Object.entries(guide.roleGuides)) {
  add({
    source: 'User guide',
    title: `${role} quick start`,
    audience: 'all',
    roles: [role],
    text: [
      roleGuide.roleSummary,
      `${roleGuide.quickStartTitle}: ${roleGuide.quickStartSummary}`,
      ...roleGuide.quickStartItems.map((item) => `- ${item}`),
      roleGuide.flowSummary,
      ...roleGuide.flowSteps.map((step) => `- ${step.title}: ${step.detail}`),
      ...roleGuide.questions.map((qa) => `Q: ${qa.question}\nA: ${qa.answer}`),
    ].join('\n'),
  });
}

add({
  source: 'User guide',
  title: 'How items advance between stages',
  audience: 'all',
  text: guide.advancementRules.map((rule) => `- ${rule.title}: ${rule.detail}`).join('\n'),
});

for (const stage of guide.flowStages) {
  add({ source: 'User guide', title: `Workflow stage: ${stage.title}`, audience: 'all', pages: stage.pages, text: `${stage.detail}\nPrimary roles: ${stage.primaryRoles.join(', ')}` });
}

for (const card of guide.pageCards) {
  add({
    source: 'User guide', title: `Page: ${card.title}`, audience: 'all', pages: card.pages,
    text: [card.summary, ...card.modules.map((m) => `- ${m}`), ...card.workflows.map((w) => `- ${w}`)].join('\n'),
  });
}

for (const card of guide.recordCards) {
  add({
    source: 'User guide', title: `Record page: ${card.title}`, audience: 'all', pages: card.pages,
    text: [card.summary, ...card.surfaces.map((s) => `- ${s}`), ...card.workflows.map((w) => `- ${w}`)].join('\n'),
  });
}

addMarkdown('docs/used-gear-workflow/operator-guide.md', 'Operator guide', 'workflow');
addMarkdown('docs/used-gear-workflow/ui-surface-map.md', 'UI surface map', 'workflow');
addMarkdown('docs/TROUBLESHOOTING.md', 'Troubleshooting', 'full-access');
addMarkdown('docs/GOTCHAS_AND_FAQ.md', 'FAQ and gotchas', 'full-access');
addMarkdown('docs/ONBOARDING_GUIDE.md', 'Onboarding guide', 'full-access');

writeFileSync(
  outFile,
  `// Generated by scripts/generate-assistant-knowledge.ts. Do not edit by hand.\nimport type { KnowledgeChunk } from './knowledge.js';\n\nexport const KNOWLEDGE_CHUNKS: KnowledgeChunk[] = ${JSON.stringify(chunks, null, 1)};\n`,
);
console.log(`Wrote ${chunks.length} knowledge chunks to ${path.relative(root, outFile)}`);
